// Helper to generate realistic historical candles with indicators
export function generateCandleHistory(basePrice: number, count: number = 60, intervalLabel: string = '1D'): Candle[] {
  const candles: Candle[] = [];
  const now = Date.now();
  const stepMs = intervalLabel === '1D' ? 5 * 60 * 1000 : intervalLabel === '1W' ? 30 * 60 * 1000 : 24 * 60 * 60 * 1000;
  
  let current = basePrice * 0.92;
  const prices: number[] = [];

  for (let i = count; i >= 0; i--) {
    const timestamp = now - i * stepMs;
    const dateObj = new Date(timestamp);
    const date = intervalLabel === '1D' 
      ? dateObj.toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' })
      : dateObj.toLocaleDateString([], { month: 'short', day: 'numeric' });

    // Geometric random walk drift
    const changeFactor = 1 + (Math.random() - 0.485) * 0.024;
    const open = current;
    const close = +(open * changeFactor).toFixed(2);
    const high = +(Math.max(open, close) * (1 + Math.random() * 0.012)).toFixed(2);
    const low = +(Math.min(open, close) * (1 - Math.random() * 0.012)).toFixed(2);
    const volume = Math.floor(Math.random() * 850000) + 120000;

    current = close;
    prices.push(close);

    // Calculate SMA 20
    let sma20: number | undefined;
    if (prices.length >= 20) {
      const slice = prices.slice(prices.length - 20);
      sma20 = +(slice.reduce((acc, v) => acc + v, 0) / 20).toFixed(2);
    }

    // Calculate EMA 50
    let ema50: number | undefined;
    if (prices.length >= 30) {
      const k = 2 / (50 + 1);
      const prevEma = candles[candles.length - 1]?.ema50 || close;
      ema50 = +(close * k + prevEma * (1 - k)).toFixed(2);
    }

    // Realistic RSI estimation based on recent closes
    let rsi: number | undefined;
    if (prices.length >= 14) {
      let gains = 0;
      let losses = 0;
      for (let j = prices.length - 14; j < prices.length; j++) {
        const diff = prices[j] - prices[j - 1];
        if (diff >= 0) gains += diff;
        else losses += Math.abs(diff);
      }
      const rs = losses === 0 ? 100 : gains / losses;
      rsi = +(100 - (100 / (1 + rs))).toFixed(1);
    }

    candles.push({
      timestamp,
      date,
      open,
      high,
      low,
      close,
      volume,
      sma20,
      ema50,
      rsi,
    });
  }

  // Anchor last candle close to actual basePrice
  if (candles.length > 0) {
    const last = candles[candles.length - 1];
    last.close = basePrice;
    last.high = Math.max(last.high, basePrice);
    last.low = Math.min(last.low, basePrice);
  }

  return candles;
}

